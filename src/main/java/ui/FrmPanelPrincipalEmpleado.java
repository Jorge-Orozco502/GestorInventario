    private void mostrarUsuarioLogeado() {
        Usuario actual = Sesion.getUsuarioActual();

        if (actual != null) {
            txtUsuarioLogeado.setText(actual.getNombreCompleto());
        } else {
            txtUsuarioLogeado.setText("Sin sesión");
        }

        txtUsuarioLogeado.setEditable(false);
    }

    private void cargarVentasDelDia() {
        Usuario actual = Sesion.getUsuarioActual();
        if (actual == null) {
            return;
        }

        List<Object[]> filas = new VentaDAO().listarVentasDelDiaPorUsuario(actual.getIdUsuario());

        javax.swing.table.DefaultTableModel modelo
                = (javax.swing.table.DefaultTableModel) tblVentasDelDia.getModel();

        modelo.setRowCount(0);
        for (Object[] fila : filas) {
            modelo.addRow(fila);
        }
    }

