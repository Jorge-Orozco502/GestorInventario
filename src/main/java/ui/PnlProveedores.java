    private void btnEditarProveedorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarProveedorActionPerformed
        if (modoEdicion) {
            try {
                Proveedor p = proveedorDesdeFormulario();

                if (proveedorDAO.actualizarProveedor(p)) {
                    cargarProveedores();
                    limpiarFormulario();
                    JOptionPane.showMessageDialog(
                            this, "Proveedor actualizado correctamente."
                    );
                } else {
                    mostrarError("No se pudo actualizar el proveedor.");
                }
            } catch (IllegalArgumentException ex) {
                mostrarError(ex.getMessage());
            }
            return;
        }

        int filaVista = tblProveedores.getSelectedRow();

        if (filaVista < 0) {
            mostrarError("Selecciona un proveedor de la tabla para editar.");
            return;
        }

        int filaModelo = tblProveedores.convertRowIndexToModel(filaVista);
        String codigo = String.valueOf(modeloTabla.getValueAt(filaModelo, 0));

        Proveedor p = proveedores.stream()
                .filter(proveedor -> proveedor.getCodigo().equals(codigo))
                .findFirst()
                .orElse(null);

        if (p == null) {
            return;
        }

        txtCodigo.setText(p.getCodigo());
        txtCodigo.setEditable(false);
        txtNombreEmpresa.setText(p.getNombreEmpresa());
        txtNit.setText(p.getNit());
        txtTelefono.setText(p.getTelefono() == null ? "" : p.getTelefono());
        txtDireccion.setText(p.getDireccion() == null ? "" : p.getDireccion());
        txtCorreo.setText(
                p.getCorreoElectronico() == null ? "" : p.getCorreoElectronico()
        );

        modoEdicion = true;
        btnEditarProveedor.setText("Guardar Cambios");
        txtNombreEmpresa.requestFocusInWindow();
    }//GEN-LAST:event_btnEditarProveedorActionPerformed

    private void btnEliminarProveedorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarProveedorActionPerformed
        int filaVista = tblProveedores.getSelectedRow();

        if (filaVista < 0) {
            mostrarError("Selecciona un proveedor de la tabla para eliminar.");
            return;
        }

        String codigo = String.valueOf(tblProveedores.getValueAt(filaVista, 0));

        int confirmar = JOptionPane.showConfirmDialog(
                this,
                "¿Eliminar el proveedor " + codigo + "?",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
        );

        if (confirmar == JOptionPane.YES_OPTION) {
            if (proveedorDAO.eliminarProveedor(codigo)) {
                cargarProveedores();
                limpiarFormulario();
            } else {
                mostrarError(
                        "No se pudo eliminar. Puede estar asociado a compras "
                        + "o no existir."
                );
            }
        }
    }//GEN-LAST:event_btnEliminarProveedorActionPerformed

    private void btnAgregarProveedorActionPerformed(java.awt.event.ActionEvent evt) {
        try {
            Proveedor p = proveedorDesdeFormulario();

            if (proveedorDAO.insertarProveedor(p)) {
                cargarProveedores();
                limpiarFormulario();
                JOptionPane.showMessageDialog(
                        this, "Proveedor agregado correctamente."
                );
            } else {
                mostrarError(
                        "No se pudo agregar. Verifica que el código y NIT no estén "
                        + "duplicados y que la base de datos esté disponible."
                );
            }
        } catch (IllegalArgumentException ex) {
            mostrarError(ex.getMessage());
        }
    }

