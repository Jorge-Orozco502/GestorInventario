    private boolean validarNitYSucursal(String nit, String direccion,
            String codigoExcluir, boolean preguntarSucursal) throws java.sql.SQLException {

        java.util.List<Cliente> existentes = clienteDAO.listarPorNit(nit);
        existentes.removeIf(c -> c.getCodigoCliente().equals(codigoExcluir));

        if (existentes.isEmpty()) {
            return true;
        }

        if (nit.equals("CF")) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "El NIT CF está reservado para el cliente Consumidor Final.\n"
                    + "El nombre y la dirección de esos clientes se anotan en cada venta.",
                    "NIT CF", javax.swing.JOptionPane.WARNING_MESSAGE);
            return false;
        }

        if (clienteDAO.buscarMismaSucursal(nit, direccion, codigoExcluir) != null) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ya existe un cliente con este NIT y esta misma dirección.\n"
                    + "No se puede registrar dos veces.",
                    "Cliente duplicado", javax.swing.JOptionPane.WARNING_MESSAGE);
            return false;
        }

        if (!preguntarSucursal) {
            return true;
        }

        if (direccion.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Este NIT ya está registrado.\n"
                    + "Escribe la dirección para distinguir la sucursal.",
                    "Falta la dirección", javax.swing.JOptionPane.WARNING_MESSAGE);
            return false;
        }

        Cliente referencia = existentes.get(0);
        String dondeEsta = (referencia.getDireccion() == null || referencia.getDireccion().isBlank())
                ? "(sin dirección)" : referencia.getDireccion();

        int respuesta = javax.swing.JOptionPane.showConfirmDialog(this,
                "Ya existe " + referencia.getNombreCliente() + " con este NIT en " + dondeEsta
                + ".\n¿Es otra sucursal?",
                "NIT ya registrado",
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.QUESTION_MESSAGE);

        return respuesta == javax.swing.JOptionPane.YES_OPTION;
    }

