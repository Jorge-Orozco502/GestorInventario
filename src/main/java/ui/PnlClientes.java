    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        try {
            String codigoNuevo = txtCodigo.getText().trim();
            String nombre = txtNombreCliente.getText().trim();
            String nit = ClienteDAO.normalizarNit(txtNitCliente.getText());
            String telefono = txtTelefonoCliente.getText().trim();
            String direccion = txtDireccionCliente.getText().trim();

            if (codigoOriginal.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Debe seleccionar un cliente de la tabla para actualizar.");
                return;
            }

            if (codigoNuevo.isEmpty() || nombre.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "El código y el nombre son obligatorios.");
                return;
            }

            if (nit.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "El NIT es obligatorio. Si el cliente no tiene NIT, escribe CF.");
                return;
            }

            if (!validarNitYSucursal(nit, direccion, codigoNuevo, false)) {
                return;
            }

            Cliente clienteModificado = new Cliente(codigoNuevo, nombre, telefono, nit, direccion);

            boolean resultado = clienteDAO.actualizarCliente(clienteModificado);

            if (resultado) {
                javax.swing.JOptionPane.showMessageDialog(this, "Cliente actualizado exitosamente.");
                cargarTablaClientes();
                limpiarFormulario();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "No se pudo actualizar el cliente.");
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

