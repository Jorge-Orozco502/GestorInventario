    private void btnAgregarClienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarClienteActionPerformed
        // TODO add your handling code here:
        try {
            String codigo = txtCodigo.getText().trim();
            String nombre = txtNombreCliente.getText().trim();
            String nit = ClienteDAO.normalizarNit(txtNitCliente.getText());
            String telefono = txtTelefonoCliente.getText().trim();
            String direccion = txtDireccionCliente.getText().trim();

            if (nombre.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "El nombre es obligatorio.");
                return;
            }

            if (nit.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "El NIT es obligatorio. Si el cliente no tiene NIT, escribe CF.");
                return;
            }

            if (!validarNitYSucursal(nit, direccion, null, true)) {
                return;
            }

            Cliente nuevoCliente = new Cliente(codigo, nombre, telefono, nit, direccion);

            boolean resultado;
            if (codigo.isEmpty()) {
                clienteDAO.registrarConCodigoAutomatico(nuevoCliente);
                resultado = true;
            } else {
                resultado = clienteDAO.insertarCliente(nuevoCliente);
            }

            if (resultado) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Cliente agregado exitosamente.\nCódigo: " + nuevoCliente.getCodigoCliente());
                cargarTablaClientes();
                limpiarFormulario();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "No se pudo registrar el cliente.");
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnAgregarClienteActionPerformed

